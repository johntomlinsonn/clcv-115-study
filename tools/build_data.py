def section(start, end):
    i = SPEC.index(start)
    j = SPEC.index(end, i + len(start))
    return SPEC[i:j]


def inline_md(s):
    s = re.sub(r"\*\*\*(.+?)\*\*\*", r"<b><i>\1</i></b>", s)
    s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
    s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<i>\1</i>", s)
    return s.replace("</b></i>", "</i></b>")


def plain(s):
    s = re.sub(r"\*\*(.+?)\*\*", r"\1", s)
    s = re.sub(r"\*(.+?)\*", r"\1", s)
    return s.strip()


def write_js(name, var, data):
    out = ROOT / "data" / name
    body = json.dumps(data, ensure_ascii=False, indent=1)
    out.write_text(f"// Generated by tools/build_data.py from docs/claude-study-website-design.md\nwindow.{var} = {body};\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


