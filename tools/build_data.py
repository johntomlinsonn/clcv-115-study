def md_block_to_html(lines):
    html, stack = [], []  # stack of (indent, tag)
    for raw in lines:
        if not raw.strip():
            continue
        m = re.match(r"^(\s*)(- |\d+\. )(.*)$", raw)
        if not m:
            while stack:
                html.append(f"</{stack.pop()[1]}>")
            html.append(f"<p>{inline_md(raw.strip())}</p>")
            continue
        ind, marker, text = len(m.group(1)), m.group(2), m.group(3)
        tag = "ol" if marker[0].isdigit() else "ul"
        while stack and stack[-1][0] > ind:
            html.append(f"</{stack.pop()[1]}>")
        if not stack or stack[-1][0] < ind:
            html.append(f"<{tag}>")
            stack.append((ind, tag))
        elif stack[-1][1] != tag:
            html.append(f"</{stack.pop()[1]}>")
            html.append(f"<{tag}>")
            stack.append((ind, tag))
        html.append(f"<li>{inline_md(text)}</li>")
    while stack:
        html.append(f"</{stack.pop()[1]}>")
    return "\n".join(html)


