def auto_why(qtext, correct):
    # prefer a term named in the correct answer, then one named in the question
    for hay in (plain(correct), plain(qtext)):
        for name, t in term_index:
            for alias in name.replace("&", "/").split("/"):
                alias = alias.split("(")[0].strip()
                if len(alias) >= 4 and re.search(r"\b" + re.escape(alias) + r"\b", hay):
                    return f"{t['term']}: {t['guide']}."
    return ""


